#!/usr/bin/env bash
# Sets up Rauthy locally for mnemograph development:
#   1. generates dev/rauthy/config.toml and the bootstrap API key (once; git-ignored),
#   2. starts Rauthy on http://localhost:8180,
#   3. creates the scope "mnemograph" and the pre-registered public client "claude-code".
# Safe to run again: existing config, scope and client are kept or updated.
set -euo pipefail

cd "$(dirname "$0")"
RAUTHY_URL="http://localhost:8180"
MNEMOGRAPH_RESOURCE="${MNEMOGRAPH_RESOURCE:-http://localhost:8080/mcp}"
CONFIG_DIR="rauthy"
SECRETS="$CONFIG_DIR/secrets.env"

for tool in docker curl jq openssl; do
  command -v "$tool" > /dev/null || { echo "missing tool: $tool" >&2; exit 1; }
done

if [[ ! -f "$SECRETS" ]]; then
  echo "Generating Rauthy config in dev/$CONFIG_DIR/ ..."
  mkdir -p "$CONFIG_DIR/bootstrap"
  admin_password="$(openssl rand -base64 18 | tr -d '/+=')"
  api_secret="$(openssl rand -hex 32)"
  key_id="$(openssl rand -hex 4)"
  cat > "$SECRETS" <<SECRETS_EOF
ADMIN_EMAIL=admin@localhost
ADMIN_PASSWORD=$admin_password
API_KEY='bootstrap\$$api_secret'
SECRETS_EOF
  cat > "$CONFIG_DIR/config.toml" <<CONFIG_EOF
# Generated by dev/setup-rauthy.sh for local development only.
[bootstrap]
admin_email = "admin@localhost"
password_plain = "$admin_password"
bootstrap_dir = "bootstrap"

[cluster]
node_id = 1
nodes = ["1 localhost:8100 localhost:8200"]
secret_raft = "$(openssl rand -hex 16)"
secret_api = "$(openssl rand -hex 16)"

[encryption]
keys = ["$key_id/$(openssl rand -base64 32)"]
key_active = "$key_id"

[access]
# Plain http on localhost needs non-__Host- cookies.
cookie_mode = "danger-insecure"
# Loopback redirect URIs match any port (RFC 8252), so Claude Code can pick its callback port.
rfc_8252_enable = true
# Allow refreshing before the access token is about to expire (Rauthy issue #1647).
disable_refresh_token_nbf = true

[server]
scheme = "http"
port_http = 8180
pub_url = "localhost:8180"
proxy_mode = false

[webauthn]
rp_id = "localhost"
rp_origin = "$RAUTHY_URL"
CONFIG_EOF
  cat > "$CONFIG_DIR/bootstrap/api_keys.json" <<KEYS_EOF
[
  {
    "name": "bootstrap",
    "exp": 4102444800,
    "secret": { "Plain": "$api_secret" },
    "access": [
      { "group": "Clients", "access_rights": ["read", "create", "update", "delete"] },
      { "group": "Scopes", "access_rights": ["read", "create", "update", "delete"] }
    ]
  }
]
KEYS_EOF
  # Rauthy runs as uid 10001 in the container and must read the mounted files.
  chmod 644 "$CONFIG_DIR/config.toml" "$CONFIG_DIR/bootstrap/api_keys.json"
  chmod 600 "$SECRETS"
fi
# shellcheck disable=SC1090
source "$SECRETS"

echo "Starting Rauthy ..."
docker compose up -d rauthy
for _ in $(seq 1 60); do
  curl -sf "$RAUTHY_URL/auth/v1/.well-known/openid-configuration" > /dev/null && break
  sleep 1
done
curl -sf "$RAUTHY_URL/auth/v1/.well-known/openid-configuration" > /dev/null \
  || { echo "Rauthy did not come up; see: docker compose -f dev/compose.yaml logs rauthy" >&2; exit 1; }

api() { # method path [json] -> prints the HTTP status
  local args=(-s -o /dev/null -w '%{http_code}' -X "$1" "$RAUTHY_URL/auth/v1$2"
    -H "Authorization: API-Key $API_KEY" -H 'Content-Type: application/json')
  if [[ $# -ge 3 ]]; then args+=(-d "$3"); fi
  curl "${args[@]}"
}

if [[ "$(api GET /scopes)" != 200 ]]; then
  echo "The bootstrap API key does not work. Rauthy reads bootstrap files only on its first start;" >&2
  echo "to start over: docker compose -f dev/compose.yaml down -v && rm -r dev/rauthy" >&2
  exit 1
fi

existing_scopes="$(curl -sf "$RAUTHY_URL/auth/v1/scopes" -H "Authorization: API-Key $API_KEY")"
if ! jq -e '.[] | select(.name == "mnemograph")' <<< "$existing_scopes" > /dev/null; then
  status="$(api POST /scopes '{"scope":"mnemograph"}')"
  [[ "$status" == 200 ]] || { echo "creating the scope failed: HTTP $status" >&2; exit 1; }
fi

# Pre-registered public client for Claude Code: authorization code + PKCE (S256),
# loopback callback on any port, tokens for mnemograph's MCP endpoint (RFC 8707).
if [[ "$(api GET /clients/claude-code)" != 200 ]]; then
  status="$(api POST /clients \
    '{"id":"claude-code","name":"Claude Code","confidential":false,"redirect_uris":["http://localhost/callback"]}')"
  [[ "$status" == 200 ]] || { echo "creating the client failed: HTTP $status" >&2; exit 1; }
fi
# The PUT replaces the whole client; omitting "challenges" would switch off PKCE.
client="$(jq -n --arg resource "$MNEMOGRAPH_RESOURCE" '{
  name: "Claude Code",
  confidential: false,
  enabled: true,
  redirect_uris: ["http://localhost/callback", "http://127.0.0.1/callback"],
  flows_enabled: ["authorization_code", "refresh_token"],
  access_token_alg: "EdDSA",
  id_token_alg: "EdDSA",
  auth_code_lifetime: 60,
  access_token_lifetime: 1800,
  scopes: ["openid", "profile", "email", "mnemograph"],
  default_scopes: ["openid", "mnemograph"],
  challenges: ["S256"],
  force_mfa: false,
  allowed_resources: [$resource],
  default_aud: []
}')"
status="$(api PUT /clients/claude-code "$client")"
[[ "$status" == 200 ]] || { echo "configuring the client failed: HTTP $status" >&2; exit 1; }

cat <<DONE

Rauthy is ready at $RAUTHY_URL (admin UI: $RAUTHY_URL/auth/v1/admin)
  admin login:  $ADMIN_EMAIL / $ADMIN_PASSWORD   (also in dev/$SECRETS)
  issuer:       $RAUTHY_URL/auth/v1/
  client:       claude-code (public, PKCE), resource $MNEMOGRAPH_RESOURCE

Next:
  cargo run -- serve --oidc-issuer $RAUTHY_URL/auth/v1/
  claude mcp add --transport http --client-id claude-code mnemograph $MNEMOGRAPH_RESOURCE
  claude mcp login mnemograph      # or /mcp inside a Claude Code session
DONE
