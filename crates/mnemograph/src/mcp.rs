/// Sent to agents when they connect, before the usage page hint: what mnemograph is.
const ABOUT: &str = "\
mnemograph is the long-term memory shared by its owner and their AI agents. It holds:
- pages: one per subject (a project, technology, decision, person, tool or concept), identified by a \
case-insensitive title, optionally with aliases and a page type;
- notes: short, timestamped, append-only records that link to the pages they concern.";

/// The page with the owner's filing conventions. The instructions point agents to it while it
/// exists (by title or alias), so a fresh installation never sends them to a missing page.
pub const USAGE_PAGE: &str = "Using mnemograph";

/// Sent to agents when they connect, after the usage page hint: how to work with mnemograph.
const INSTRUCTIONS: &str = "\
How to work with it:
1. Before starting a task, search for its subject and for the project you work on, and read the \
pages you find. read_page shows a page's links, backlinks and recent notes; related shows what is \
around it.
2. Reuse existing pages. Before creating a page, search for its subject: if it exists under another \
name, link to that title or add an alias instead of creating a near-duplicate.
3. Record decisions, findings and notable events as notes with add_note when they happen: state what \
and why, and link the pages concerned with [[Title]] - always including the project's page. Linking a \
title that has no page yet is fine; it becomes a stub that a page can fill later.
4. Keep durable knowledge in pages, written with write_page. To change a page, read it, then send \
the complete new body with its revision as base_revision. If someone changed it meanwhile, the error contains the current \
revision: merge your change into it and retry.
5. Never store secrets such as passwords, tokens or private keys.
6. You cannot delete anything; tell the owner if something should be removed.";

/// How many recent notes read_page returns.
const RECENT_NOTES: u32 = 10;
/// How many entries related returns at most.
const RELATED_LIMIT: u32 = 50;
/// Default and maximum number of search hits.
const SEARCH_LIMIT: (i64, i64) = (10, 50);

/// The MCP server; one instance is created per request.
#[derive(Clone)]
pub struct McpServer {
    knowledge: Arc<Knowledge>,
    limiter: Arc<Limiter>,
    /// Counts writes, so open web views can update themselves.
    changes: Arc<tokio::sync::watch::Sender<u64>>,
    #[allow(dead_code, reason = "read by the code generated by #[tool_handler]")]
    tool_router: ToolRouter<Self>,
}

/// A page as returned to agents.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct PageView {
    pub title: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub page_type: Option<String>,
    /// Alternative titles that lead to this page.
    pub aliases: Vec<String>,
    /// Markdown body.
    pub body: String,
    /// Current revision number; pass it as `base_revision` when changing the page.
    pub revision: i64,
    pub created_at: String,
    pub updated_at: String,
    /// Who wrote the current revision: "owner:<user>", "agent:<client>" or "anonymous".
    #[serde(skip_serializing_if = "Option::is_none")]
    pub updated_by: Option<String>,
    /// Titles this page links to, in order of appearance.
    pub links: Vec<LinkView>,
    /// Titles of the pages linking to this page.
    pub backlinks: Vec<String>,
    /// The most recent notes linking to this page, newest first.
    pub notes: Vec<NoteView>,
}

/// A note as returned to agents.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct NoteView {
    pub id: i64,
    pub body: String,
    pub created_at: String,
    /// Who recorded the note: "owner:<user>", "agent:<client>" or "anonymous".
    #[serde(skip_serializing_if = "Option::is_none")]
    pub author: Option<String>,
    /// Titles the note links to.
    pub links: Vec<LinkView>,
}

impl From<Note> for NoteView {
    fn from(note: Note) -> Self {
        Self {
            id: note.id,
            body: note.body,
            created_at: note.created_at,
            author: note.author.as_ref().map(ToString::to_string),
            links: note.links.into_iter().map(LinkView::from).collect(),
        }
    }
}

/// A link from a page to a title.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct LinkView {
    /// The title as written in the link.
    pub title: String,
    /// True if no page has this title or alias yet; writing a page with this title fills the stub.
    pub stub: bool,
    /// Title of the page the link leads to, if it differs from the link's title (case or alias).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub page: Option<String>,
}

impl From<LinkTarget> for LinkView {
    fn from(link: LinkTarget) -> Self {
        Self {
            stub: link.is_stub(),
            page: link.page.filter(|page| *page != link.title),
            title: link.title,
        }
    }
}

impl PageView {
    fn new(page: Page, links: Links, notes: Vec<Note>) -> Self {
        Self {
            title: page.title,
            page_type: page.page_type,
            aliases: page.aliases,
            body: page.body,
            revision: page.revision.into(),
            created_at: page.created_at,
            updated_at: page.updated_at,
            updated_by: page.author.as_ref().map(ToString::to_string),
            links: links.outgoing.into_iter().map(LinkView::from).collect(),
            backlinks: links.backlinks,
            notes: notes.into_iter().map(NoteView::from).collect(),
        }
    }
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct WritePageArgs {
    /// Title or alias of the page: the name of its subject, e.g. "Rauthy". Case-insensitive; must
    /// not contain [ ] | or line breaks.
    pub title: String,
    /// The complete new Markdown body of the page (not a diff). Link to other pages with
    /// [[Title]] or [[Title|label]].
    pub body: String,
    /// Required to change an existing page: the revision your new body is based on, as returned
    /// by read_page. Omit it only to create a new page.
    #[serde(default)]
    pub base_revision: Option<i64>,
    /// Renames the page. The old title stays an alias, so existing links keep working.
    #[serde(default)]
    pub new_title: Option<String>,
    /// Page type, one of the types listed in the server instructions. Omit to keep the current
    /// type; an empty string removes it.
    #[serde(default)]
    pub page_type: Option<String>,
    /// Replaces all aliases (alternative titles leading to this page). Omit to keep them.
    #[serde(default)]
    pub aliases: Option<Vec<String>>,
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct AddNoteArgs {
    /// The note in Markdown: what happened or was decided, and why. Link the pages it concerns
    /// with [[Title]]; titles without a page yet are fine.
    pub body: String,
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct SearchArgs {
    /// Words to search for. Matches German and English word forms ("Datenbanken" finds
    /// "Datenbank", "databases" finds "database"). Use "quotes" for phrases.
    pub query: String,
    /// Only search pages of this page type (notes are then excluded).
    #[serde(default)]
    pub page_type: Option<String>,
    /// Maximum number of hits, 1 to 50. Defaults to 10.
    #[serde(default)]
    pub limit: Option<i64>,
}

/// Search results, best match first.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct SearchView {
    pub hits: Vec<HitView>,
}

/// A page or note that matched a search.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
#[serde(tag = "kind", rename_all = "lowercase")]
pub enum HitView {
    Page {
        title: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        page_type: Option<String>,
        /// The matching part of the page, with matched words in **bold**.
        snippet: String,
    },
    Note {
        note: NoteView,
        /// The matching part of the note, with matched words in **bold**.
        snippet: String,
    },
}

impl From<SearchHit> for HitView {
    fn from(hit: SearchHit) -> Self {
        match hit.found {
            Found::Page { title, page_type } => HitView::Page {
                title,
                page_type,
                snippet: hit.snippet,
            },
            Found::Note(note) => HitView::Note {
                note: note.into(),
                snippet: hit.snippet,
            },
        }
    }
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct RelatedArgs {
    /// Title or alias of the page or stub to start from.
    pub title: String,
    /// How many links away to look, 1 to 3. Defaults to 2.
    #[serde(default)]
    pub hops: Option<i64>,
}

/// The neighborhood of a page in the link graph.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct RelatedView {
    /// Pages and stubs near the starting point, nearest first.
    pub related: Vec<RelatedEntry>,
}

/// A page or stub near another one.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct RelatedEntry {
    pub title: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub page_type: Option<String>,
    /// True if no page has this title yet.
    pub stub: bool,
    /// Number of links between the two, following links in either direction.
    pub distance: i64,
}

impl From<Related> for RelatedEntry {
    fn from(related: Related) -> Self {
        Self {
            title: related.title,
            page_type: related.page_type,
            stub: related.stub,
            distance: related.distance.into(),
        }
    }
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct ReadPageArgs {
    /// Title or alias of the page (case-insensitive).
    pub title: String,
}

#[tool_router]
impl McpServer {
    pub fn new(
        knowledge: Arc<Knowledge>,
        limiter: Arc<Limiter>,
        changes: Arc<tokio::sync::watch::Sender<u64>>,
    ) -> Self {
        Self {
            knowledge,
            limiter,
            changes,
            tool_router: Self::tool_router(),
        }
    }

    #[tool(
        description = "Create a page, or change an existing one. To create, omit base_revision (fails if the title or an alias already exists). To change, send the complete new body (not a diff) and the page's current revision as base_revision; omitted page_type and aliases stay as they are. If the page changed in the meantime, the write is rejected and the error contains the current revision: merge your change into it and retry with that revision. Returns the page with its links, marking stubs."
    )]
    async fn write_page(
        &self,
        Parameters(args): Parameters<WritePageArgs>,
        Extension(request): Extension<http::request::Parts>,
    ) -> Result<rmcp::Json<PageView>, String> {
        let base_revision = args
            .base_revision
            .map(|base| u32::try_from(base).map_err(|_| format!("invalid base_revision {base}")))
            .transpose()?;
        let author = author(&request)?;
        self.limiter.check_page(&args.body)?;
        self.limiter.count_write(&author)?;
        let knowledge = self.knowledge.clone();
        blocking(move || {
            let changes = PageChanges {
                new_title: args.new_title,
                page_type: args
                    .page_type
                    .map(|t| Some(t).filter(|t| !t.trim().is_empty())),
                aliases: args.aliases,
            };
            let page =
                knowledge.write_page(&args.title, &args.body, base_revision, changes, &author)?;
            let links = knowledge.links(&page.title)?;
            let notes = knowledge.notes_about(&page.title, RECENT_NOTES)?;
            Ok(PageView::new(page, links, notes))
        })
        .await
        .inspect(|_| self.changed())
        .map(rmcp::Json)
    }

    #[tool(
        description = "Read a page by its title or an alias (case-insensitive): its body, revision, type, aliases, the titles it links to, the pages linking to it and its most recent notes. For a stub (a title that is linked but has no page yet) the error says what links to it."
    )]
    async fn read_page(
        &self,
        Parameters(args): Parameters<ReadPageArgs>,
        Extension(request): Extension<http::request::Parts>,
    ) -> Result<rmcp::Json<PageView>, String> {
        let knowledge = self.knowledge.clone();
        let title = args.title;
        let reader = reader(&request);
        let (page, links, notes) = blocking({
            let title = title.clone();
            move || {
                let page = knowledge.page(&title)?;
                log_access(
                    &knowledge,
                    reader,
                    Access::ReadPage,
                    &title,
                    page.is_some().into(),
                );
                Ok((
                    page,
                    knowledge.links(&title)?,
                    knowledge.notes_about(&title, RECENT_NOTES)?,
                ))
            }
        })
        .await?;
        match page {
            Some(page) => Ok(rmcp::Json(PageView::new(page, links, notes))),
            None if links.backlinks.is_empty() && notes.is_empty() => {
                Err(format!("no page titled {title:?}"))
            }
            None => Err(stub_message(&title, &links.backlinks, &notes)),
        }
    }

    #[tool(
        description = "Search pages (titles, aliases, bodies) and notes by full text, best matches first, each with a snippet. Understands German and English word forms. Use it before starting a task and before creating a page."
    )]
    async fn search(
        &self,
        Parameters(args): Parameters<SearchArgs>,
        Extension(request): Extension<http::request::Parts>,
    ) -> Result<rmcp::Json<SearchView>, String> {
        let knowledge = self.knowledge.clone();
        let reader = reader(&request);
        let limit = args
            .limit
            .unwrap_or(SEARCH_LIMIT.0)
            .clamp(1, SEARCH_LIMIT.1) as usize;
        let page_type = args.page_type.filter(|t| !t.trim().is_empty());
        blocking(move || {
            let hits = knowledge.search(&args.query, page_type.as_deref(), limit)?;
            log_access(&knowledge, reader, Access::Search, &args.query, hits.len());
            Ok(hits)
        })
        .await
        .map(|hits| {
            rmcp::Json(SearchView {
                hits: hits.into_iter().map(HitView::from).collect(),
            })
        })
    }

    #[tool(
        description = "Find what else is known around a subject: the pages and stubs within a few links of a page, following links in both directions, nearest first."
    )]
    async fn related(
        &self,
        Parameters(args): Parameters<RelatedArgs>,
        Extension(request): Extension<http::request::Parts>,
    ) -> Result<rmcp::Json<RelatedView>, String> {
        let knowledge = self.knowledge.clone();
        let reader = reader(&request);
        let hops = args.hops.unwrap_or(2).clamp(1, MAX_HOPS.into()) as u32;
        blocking(move || {
            let related = knowledge.related(&args.title, hops, RELATED_LIMIT);
            let hits = related.as_ref().map(Vec::len).unwrap_or(0);
            log_access(&knowledge, reader, Access::Related, &args.title, hits);
            related
        })
        .await
        .map(|related| {
            rmcp::Json(RelatedView {
                related: related.into_iter().map(RelatedEntry::from).collect(),
            })
        })
    }

    #[tool(
        description = "Record a note: a short, timestamped, append-only entry such as a decision, finding or event. [[Title]] links attach it to the pages it concerns, where read_page shows it."
    )]
    async fn add_note(
        &self,
        Parameters(args): Parameters<AddNoteArgs>,
        Extension(request): Extension<http::request::Parts>,
    ) -> Result<rmcp::Json<NoteView>, String> {
        let knowledge = self.knowledge.clone();
        let author = author(&request)?;
        self.limiter.check_note(&args.body)?;
        self.limiter.count_write(&author)?;
        blocking(move || knowledge.add_note(&args.body, &author))
            .await
            .inspect(|_| self.changed())
            .map(|note| rmcp::Json(note.into()))
    }
}

impl McpServer {
    /// Tells open web views that something was written.
    fn changed(&self) {
        self.changes.send_modify(|count| *count += 1);
    }

    /// Points agents to the usage page by its current title, or nothing while it doesn't exist.
    fn usage_hint(&self) -> String {
        match self.knowledge.page(USAGE_PAGE) {
            Ok(Some(page)) => format!(
                "Start here: the page \"{}\" holds the owner's conventions for filing knowledge \
                 (hub pages, decision pages, notes versus pages). Read it with read_page at the \
                 start of a session, before your first write, and follow it together with the \
                 rules below.\n\n",
                page.title
            ),
            Ok(None) => String::new(),
            Err(error) => {
                tracing::warn!(%error, "could not look up the usage page");
                String::new()
            }
        }
    }
}

#[tool_handler]
impl ServerHandler for McpServer {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new("mnemograph", env!("CARGO_PKG_VERSION")))
            .with_instructions(format!(
                "{ABOUT}\n\n{}{INSTRUCTIONS}\n\nAllowed page types: {}.",
                self.usage_hint(),
                self.knowledge.page_types().join(", ")
            ))
    }
}

/// Who reads, for the access log: the authenticated identity, if any.
fn reader(request: &http::request::Parts) -> Option<Author> {
    request
        .extensions
        .get::<Identity>()
        .map(|identity| identity.author.clone())
}

/// Records a read, search or exploration in the access log. A failure is only logged: it must
/// never fail the agent's call.
fn log_access(
    knowledge: &Knowledge,
    reader: Option<Author>,
    access: Access,
    target: &str,
    hits: usize,
) {
    let Some(reader) = reader else { return };
    let hits = u32::try_from(hits).unwrap_or(u32::MAX);
    if let Err(error) = knowledge.record_access(&reader, access, target, hits) {
        tracing::warn!(%error, "could not record an access");
    }
}

/// The author of a write: the identity the authentication middleware attached to the request.
/// Without one the write is refused, so a misconfigured router can never record a wrong author.
fn author(request: &http::request::Parts) -> Result<Author, String> {
    match request.extensions.get::<Identity>() {
        Some(identity) => Ok(identity.author.clone()),
        None => {
            tracing::error!("request without identity reached a tool");
            Err("internal error".to_owned())
        }
    }
}

/// Explains that `title` is a stub, with what links to it.
fn stub_message(title: &str, backlinks: &[String], notes: &[Note]) -> String {
    let mut message = format!("no page titled {title:?} yet; it is a stub");
    if !backlinks.is_empty() {
        message += &format!(" linked from the pages: {}", backlinks.join(", "));
    }
    if !notes.is_empty() {
        let notes = serde_json::to_string(
            &notes
                .iter()
                .cloned()
                .map(NoteView::from)
                .collect::<Vec<_>>(),
        )
        .expect("notes serialize");
        message += &format!(". Recent notes about it: {notes}");
    }
    message + ". Create it with write_page."
}

/// Turns a domain error into a message the agent can act on.
fn agent_message(err: mnemograph_core::Error) -> String {
    match err {
        mnemograph_core::Error::Conflict { ref current, .. } => {
            let current = serde_json::json!({
                "title": current.title,
                "page_type": current.page_type,
                "aliases": current.aliases,
                "revision": current.revision,
                "body": current.body,
            });
            format!("{err}. Current revision: {current}")
        }
        mnemograph_core::Error::Storage(_) | mnemograph_core::Error::Migration(_) => {
            tracing::error!(%err, "knowledge operation failed");
            "internal error".to_owned()
        }
        _ => err.to_string(),
    }
}

/// Runs a synchronous [`Knowledge`] call on the blocking thread pool and turns domain errors
/// into messages for the agent.
async fn blocking<T: Send + 'static>(
    f: impl FnOnce() -> mnemograph_core::Result<T> + Send + 'static,
) -> Result<T, String> {
    match tokio::task::spawn_blocking(f).await {
        Ok(result) => result.map_err(agent_message),
        Err(join_error) => {
            tracing::error!(%join_error, "knowledge task failed");
            Err("internal error".to_owned())
        }
    }
}
