//! MCP tools for agents.

use std::sync::Arc;

use mnemograph_core::{Knowledge, LinkTarget, Links, MAX_HOPS, Note, Page, PageChanges, Related};
use rmcp::{
    ServerHandler,
    handler::server::{router::tool::ToolRouter, wrapper::Parameters},
    model::{Implementation, ServerCapabilities, ServerConfig},
    schemars, tool, tool_handler, tool_router,
};
use serde::{Deserialize, Serialize};

const INSTRUCTIONS: &str = "mnemograph is a long-term memory shared between agents and its owner. \
Knowledge is organized in pages, each about one subject and identified by its title. \
Titles are case-insensitive, and a page can have aliases that lead to it. \
Use read_page to look up what is already known about a subject before writing, and write_page to record new pages. \
Use add_note for short, timestamped records such as decisions, findings or events; link the pages they concern with [[Title]]. \
Notes are append-only and appear on the pages they link to.";

/// How many recent notes read_page returns.
const RECENT_NOTES: u32 = 10;
/// How many entries related returns at most.
const RELATED_LIMIT: u32 = 50;

/// The MCP server; one instance is created per request.
#[derive(Clone)]
pub struct McpServer {
    knowledge: Arc<Knowledge>,
    #[allow(dead_code, reason = "read by the code generated by #[tool_handler]")]
    tool_router: ToolRouter<Self>,
}

/// A page as returned to agents.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct PageView {
    pub title: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub page_type: Option<String>,
    /// Alternative titles that lead to this page.
    pub aliases: Vec<String>,
    /// Markdown body.
    pub body: String,
    /// Current revision number; pass it as `base_revision` when changing the page.
    pub revision: i64,
    pub created_at: String,
    pub updated_at: String,
    /// Titles this page links to, in order of appearance.
    pub links: Vec<LinkView>,
    /// Titles of the pages linking to this page.
    pub backlinks: Vec<String>,
    /// The most recent notes linking to this page, newest first.
    pub notes: Vec<NoteView>,
}

/// A note as returned to agents.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct NoteView {
    pub id: i64,
    pub body: String,
    pub created_at: String,
    /// Titles the note links to.
    pub links: Vec<LinkView>,
}

impl From<Note> for NoteView {
    fn from(note: Note) -> Self {
        Self {
            id: note.id,
            body: note.body,
            created_at: note.created_at,
            links: note.links.into_iter().map(LinkView::from).collect(),
        }
    }
}

/// A link from a page to a title.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct LinkView {
    /// The title as written in the link.
    pub title: String,
    /// True if no page has this title or alias yet; writing a page with this title fills the stub.
    pub stub: bool,
    /// Title of the page the link leads to, if it differs from the link's title (case or alias).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub page: Option<String>,
}

impl From<LinkTarget> for LinkView {
    fn from(link: LinkTarget) -> Self {
        Self {
            stub: link.is_stub(),
            page: link.page.filter(|page| *page != link.title),
            title: link.title,
        }
    }
}

impl PageView {
    fn new(page: Page, links: Links, notes: Vec<Note>) -> Self {
        Self {
            title: page.title,
            page_type: page.page_type,
            aliases: page.aliases,
            body: page.body,
            revision: page.revision.into(),
            created_at: page.created_at,
            updated_at: page.updated_at,
            links: links.outgoing.into_iter().map(LinkView::from).collect(),
            backlinks: links.backlinks,
            notes: notes.into_iter().map(NoteView::from).collect(),
        }
    }
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct WritePageArgs {
    /// Title or alias of the page: the name of its subject, e.g. "Rauthy". Case-insensitive; must
    /// not contain [ ] | or line breaks.
    pub title: String,
    /// The complete new Markdown body of the page (not a diff). Link to other pages with
    /// [[Title]] or [[Title|label]].
    pub body: String,
    /// Required to change an existing page: the revision your new body is based on, as returned
    /// by read_page. Omit it only to create a new page.
    #[serde(default)]
    pub base_revision: Option<i64>,
    /// Renames the page. The old title stays an alias, so existing links keep working.
    #[serde(default)]
    pub new_title: Option<String>,
    /// Page type, one of the types listed in the server instructions. Omit to keep the current
    /// type; an empty string removes it.
    #[serde(default)]
    pub page_type: Option<String>,
    /// Replaces all aliases (alternative titles leading to this page). Omit to keep them.
    #[serde(default)]
    pub aliases: Option<Vec<String>>,
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct AddNoteArgs {
    /// The note in Markdown: what happened or was decided, and why. Link the pages it concerns
    /// with [[Title]]; titles without a page yet are fine.
    pub body: String,
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct RelatedArgs {
    /// Title or alias of the page or stub to start from.
    pub title: String,
    /// How many links away to look, 1 to 3. Defaults to 2.
    #[serde(default)]
    pub hops: Option<i64>,
}

/// The neighborhood of a page in the link graph.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct RelatedView {
    /// Pages and stubs near the starting point, nearest first.
    pub related: Vec<RelatedEntry>,
}

/// A page or stub near another one.
#[derive(Debug, Serialize, Deserialize, schemars::JsonSchema)]
pub struct RelatedEntry {
    pub title: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub page_type: Option<String>,
    /// True if no page has this title yet.
    pub stub: bool,
    /// Number of links between the two, following links in either direction.
    pub distance: i64,
}

impl From<Related> for RelatedEntry {
    fn from(related: Related) -> Self {
        Self {
            title: related.title,
            page_type: related.page_type,
            stub: related.stub,
            distance: related.distance.into(),
        }
    }
}

#[derive(Debug, Deserialize, schemars::JsonSchema)]
pub struct ReadPageArgs {
    /// Title or alias of the page (case-insensitive).
    pub title: String,
}

#[tool_router]
impl McpServer {
    pub fn new(knowledge: Arc<Knowledge>) -> Self {
        Self {
            knowledge,
            tool_router: Self::tool_router(),
        }
    }

    #[tool(
        description = "Create a page, or change an existing one by sending its complete new body together with the revision it is based on. If the page changed in the meantime, the write is rejected and the error contains the current revision: merge your change into it and retry with that revision as base_revision."
    )]
    async fn write_page(
        &self,
        Parameters(args): Parameters<WritePageArgs>,
    ) -> Result<rmcp::Json<PageView>, String> {
        let base_revision = args
            .base_revision
            .map(|base| u32::try_from(base).map_err(|_| format!("invalid base_revision {base}")))
            .transpose()?;
        let knowledge = self.knowledge.clone();
        blocking(move || {
            let changes = PageChanges {
                new_title: args.new_title,
                page_type: args
                    .page_type
                    .map(|t| Some(t).filter(|t| !t.trim().is_empty())),
                aliases: args.aliases,
            };
            let page = knowledge.write_page(&args.title, &args.body, base_revision, changes)?;
            let links = knowledge.links(&page.title)?;
            let notes = knowledge.notes_about(&page.title, RECENT_NOTES)?;
            Ok(PageView::new(page, links, notes))
        })
        .await
        .map(rmcp::Json)
    }

    #[tool(
        description = "Read a page by its title or an alias, with the titles it links to and the pages linking to it."
    )]
    async fn read_page(
        &self,
        Parameters(args): Parameters<ReadPageArgs>,
    ) -> Result<rmcp::Json<PageView>, String> {
        let knowledge = self.knowledge.clone();
        let title = args.title;
        let (page, links, notes) = blocking({
            let title = title.clone();
            move || {
                Ok((
                    knowledge.page(&title)?,
                    knowledge.links(&title)?,
                    knowledge.notes_about(&title, RECENT_NOTES)?,
                ))
            }
        })
        .await?;
        match page {
            Some(page) => Ok(rmcp::Json(PageView::new(page, links, notes))),
            None if links.backlinks.is_empty() && notes.is_empty() => {
                Err(format!("no page titled {title:?}"))
            }
            None => Err(stub_message(&title, &links.backlinks, &notes)),
        }
    }

    #[tool(
        description = "Find what else is known around a subject: the pages and stubs within a few links of a page, following links in both directions, nearest first."
    )]
    async fn related(
        &self,
        Parameters(args): Parameters<RelatedArgs>,
    ) -> Result<rmcp::Json<RelatedView>, String> {
        let knowledge = self.knowledge.clone();
        let hops = args.hops.unwrap_or(2).clamp(1, MAX_HOPS.into()) as u32;
        blocking(move || knowledge.related(&args.title, hops, RELATED_LIMIT))
            .await
            .map(|related| {
                rmcp::Json(RelatedView {
                    related: related.into_iter().map(RelatedEntry::from).collect(),
                })
            })
    }

    #[tool(
        description = "Record a note: a short, timestamped, append-only entry such as a decision, finding or event. [[Title]] links attach it to the pages it concerns, where read_page shows it."
    )]
    async fn add_note(
        &self,
        Parameters(args): Parameters<AddNoteArgs>,
    ) -> Result<rmcp::Json<NoteView>, String> {
        let knowledge = self.knowledge.clone();
        blocking(move || knowledge.add_note(&args.body))
            .await
            .map(|note| rmcp::Json(note.into()))
    }
}

#[tool_handler]
impl ServerHandler for McpServer {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new("mnemograph", env!("CARGO_PKG_VERSION")))
            .with_instructions(format!(
                "{INSTRUCTIONS} Allowed page types: {}.",
                self.knowledge.page_types().join(", ")
            ))
    }
}

/// Explains that `title` is a stub, with what links to it.
fn stub_message(title: &str, backlinks: &[String], notes: &[Note]) -> String {
    let mut message = format!("no page titled {title:?} yet; it is a stub");
    if !backlinks.is_empty() {
        message += &format!(" linked from the pages: {}", backlinks.join(", "));
    }
    if !notes.is_empty() {
        let notes = serde_json::to_string(
            &notes
                .iter()
                .cloned()
                .map(NoteView::from)
                .collect::<Vec<_>>(),
        )
        .expect("notes serialize");
        message += &format!(". Recent notes about it: {notes}");
    }
    message + ". Create it with write_page."
}

/// Turns a domain error into a message the agent can act on.
fn agent_message(err: mnemograph_core::Error) -> String {
    match err {
        mnemograph_core::Error::Conflict { ref current, .. } => {
            let current = serde_json::json!({
                "title": current.title,
                "page_type": current.page_type,
                "aliases": current.aliases,
                "revision": current.revision,
                "body": current.body,
            });
            format!("{err}. Current revision: {current}")
        }
        mnemograph_core::Error::Storage(_) | mnemograph_core::Error::Migration(_) => {
            tracing::error!(%err, "knowledge operation failed");
            "internal error".to_owned()
        }
        _ => err.to_string(),
    }
}

/// Runs a synchronous [`Knowledge`] call on the blocking thread pool and turns domain errors
/// into messages for the agent.
async fn blocking<T: Send + 'static>(
    f: impl FnOnce() -> mnemograph_core::Result<T> + Send + 'static,
) -> Result<T, String> {
    match tokio::task::spawn_blocking(f).await {
        Ok(result) => result.map_err(agent_message),
        Err(join_error) => {
            tracing::error!(%join_error, "knowledge task failed");
            Err("internal error".to_owned())
        }
    }
}
